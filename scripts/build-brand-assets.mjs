// Generates brand assets from the supplied logo and font packages.
// The logo is never redrawn: the flat grey background of the source PNG is
// keyed out to transparency and the result is trimmed. Run with `npm run brand`.
import { copyFile, mkdir, writeFile } from "node:fs/promises";
import sharp from "sharp";
import { createFontStack } from "@capsizecss/core";
import { entireMetricsCollection as metrics } from "@capsizecss/metrics/entireMetricsCollection";

const SOURCE = "brand/source/winapps-logo-original.png";
const PAPER = { r: 0xf7, g: 0xf5, b: 0xf0 };

/* ---------- Fonts: copy the four weights we ship ----------
   Kept in src/assets so Vite fingerprints them and applies the base path. */
await mkdir("src/assets/fonts", { recursive: true });
const fonts = [
  ["@fontsource/schibsted-grotesk/files/schibsted-grotesk-latin-500-normal.woff2", "schibsted-grotesk-500.woff2"],
  ["@fontsource/schibsted-grotesk/files/schibsted-grotesk-latin-600-normal.woff2", "schibsted-grotesk-600.woff2"],
  ["@fontsource/inter/files/inter-latin-400-normal.woff2", "inter-400.woff2"],
  ["@fontsource/inter/files/inter-latin-600-normal.woff2", "inter-600.woff2"],
];
for (const [from, to] of fonts) await copyFile(`node_modules/${from}`, `src/assets/fonts/${to}`);

/* ---------- Fallback metrics (prevents layout shift on font swap) ---------- */
const stacks = [
  createFontStack([metrics.schibstedGrotesk, metrics.arial], { fontFaceProperties: { fontDisplay: "swap" } }),
  createFontStack([metrics.inter, metrics.arial], { fontFaceProperties: { fontDisplay: "swap" } }),
];
await writeFile(
  "src/styles/fallback-fonts.css",
  "/* Generated by scripts/build-brand-assets.mjs. Do not edit by hand. */\n" +
    stacks.map((s) => s.fontFaces).join("\n") + "\n"
);

/* ---------- Logo: key out the grey background ---------- */
const { data, info } = await sharp(SOURCE).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const { width, height } = info;

// Background colour = median of a 12px border ring.
const ring = [];
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    if (x > 11 && x < width - 12 && y > 11 && y < height - 12) continue;
    const i = (y * width + x) * 4;
    ring.push([data[i], data[i + 1], data[i + 2]]);
  }
}
const median = (k) => ring.map((p) => p[k]).sort((a, b) => a - b)[ring.length >> 1];
const bg = [median(0), median(1), median(2)];

const LOW = 16, HIGH = 70; // distance band that ramps alpha 0 → 1 (anti-aliased edges)
const out = Buffer.alloc(data.length);
for (let i = 0; i < data.length; i += 4) {
  const d = Math.hypot(data[i] - bg[0], data[i + 1] - bg[1], data[i + 2] - bg[2]);
  const a = Math.min(1, Math.max(0, (d - LOW) / (HIGH - LOW)));
  for (let c = 0; c < 3; c++) {
    // Un-matte: remove the grey that was blended into edge pixels.
    const v = a > 0 ? (data[i + c] - (1 - a) * bg[c]) / a : 0;
    out[i + c] = Math.max(0, Math.min(255, Math.round(v)));
  }
  out[i + 3] = Math.round(a * 255);
}

const keyed = sharp(out, { raw: { width, height, channels: 4 } });
const trimmed = await keyed.png().toBuffer().then((b) => sharp(b).trim({ threshold: 1 }).png().toBuffer({ resolveWithObject: true }));
await sharp(trimmed.data).png({ compressionLevel: 9 }).toFile("src/assets/brand/logo.png");

// Split mark from wordmark at the widest fully transparent row band.
const t = await sharp(trimmed.data).raw().toBuffer({ resolveWithObject: true });
const rowEmpty = [];
for (let y = 0; y < t.info.height; y++) {
  let any = false;
  for (let x = 0; x < t.info.width; x++) if (t.data[(y * t.info.width + x) * 4 + 3] > 24) { any = true; break; }
  rowEmpty.push(!any);
}
let best = { start: 0, len: 0 }, run = null;
rowEmpty.forEach((empty, y) => {
  if (empty) run = run ?? { start: y, len: 0 }, run.len++;
  else if (run) { if (run.len > best.len) best = run; run = null; }
});
const markBuf = await sharp(trimmed.data)
  .extract({ left: 0, top: 0, width: t.info.width, height: best.start })
  .trim({ threshold: 1 })
  .png()
  .toBuffer({ resolveWithObject: true });
await sharp(markBuf.data).png({ compressionLevel: 9 }).toFile("src/assets/brand/mark.png");

/* ---------- Favicons ---------- */
await mkdir("public/brand", { recursive: true });
async function icon(size, file, { pad = 0.1, background = null } = {}) {
  const inner = Math.round(size * (1 - pad * 2));
  const m = await sharp(markBuf.data).resize(inner, inner, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }).toBuffer();
  await sharp({ create: { width: size, height: size, channels: 4, background: background ?? { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite([{ input: m, gravity: "centre" }])
    .png({ compressionLevel: 9 })
    .toFile(file);
}
await icon(32, "public/favicon-32.png", { pad: 0.02 });
await icon(180, "public/apple-touch-icon.png", { pad: 0.14, background: { ...PAPER, alpha: 1 } });
await icon(512, "public/brand/icon-512.png", { pad: 0.14, background: { ...PAPER, alpha: 1 } });

console.log(`bg=${bg} logo=${trimmed.info.width}x${trimmed.info.height} mark=${markBuf.info.width}x${markBuf.info.height} gap=${best.start}+${best.len}`);
